def tr(text: str) -> str:
    if not text:
        return text
    try:
        from .util import CONFIG
        lang = str(CONFIG.get("lang", "es"))
    except Exception:
        lang = "es"
    if lang != "es":
        return text
    hit = ES.get(text)
    if hit is not None:
        return hit
    # prefix match for messages with dynamic tails ("Couldn't parse this file: <err>")
    for k in sorted(ES, key=len, reverse=True):
        if len(k) > 10 and text.startswith(k):
            return ES[k] + text[len(k):]
    return text
